const catalogs: Record<Exclude<ResolvedLanguage, 'tr'>, Record<string, string>> = { en, es, ja, de, it, az };

export function resolveLanguage(preference: LanguagePreference): ResolvedLanguage {
  if (preference !== 'auto') return preference;
  const detected = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'en';
  const code = detected.split(/[-_]/)[0] as ResolvedLanguage;
  return ['tr', 'en', 'es', 'ja', 'de', 'it', 'az'].includes(code) ? code : 'en';
}

export function localeFor(language: ResolvedLanguage): string {
  const locales: Record<ResolvedLanguage, string> = {
    tr: 'tr-TR',
    en: 'en-US',
    es: 'es-ES',
    ja: 'ja-JP',
    de: 'de-DE',
    it: 'it-IT',
    az: 'az-Latn-AZ'
  };
  return locales[language];
}

export function translate(language: ResolvedLanguage, source: string, variables: Record<string, string | number> = {}): string {
  const template = language === 'tr' ? source : catalogs[language]?.[source] ?? en[source] ?? source;
  return template.replace(/\{(\w+)\}/g, (_match, key: string) => String(variables[key] ?? `{${key}}`));
}
